import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const b=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox'],headless:true});
const p=await b.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
let errors=[];p.on('pageerror',e=>errors.push(e.message));
await p.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
await p.getByRole('button',{name:/Start guided check/}).click();
await p.getByRole('checkbox',{name:/Compare the booking dates/}).check();
assert.equal(await p.getByRole('progressbar',{name:'Guided checklist progress'}).getAttribute('aria-valuenow'),'1');
await p.getByRole('button',{name:'Reset checklist'}).click();
assert.equal(await p.getByRole('progressbar',{name:'Guided checklist progress'}).getAttribute('aria-valuenow'),'0');
await p.screenshot({path:'/tmp/1now-interactive.png',fullPage:true});
await p.getByRole('button',{name:/Urgent Booking Conflict/}).click();
await p.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
const [dl]=await Promise.all([p.waitForEvent('download'),p.getByRole('button',{name:'Download calendar event'}).click()]);
const ics=await fs.readFile(await dl.path(),'utf8');assert.match(ics,/DTSTART;VALUE=DATE:20261110/);assert.match(ics,/DTEND;VALUE=DATE:20261115/);assert.match(ics,/Demo data only/);
await p.getByLabel('Search cases').fill('TU-84219');assert.equal(await p.getByText('1 of 1 cases').count(),1);
await p.getByLabel('Filter by status').selectOption('Resolved');await p.getByText('No cases match these filters. Try a different search or status.').waitFor();
await p.getByRole('button',{name:/Support Dashboard/}).click();await p.getByText('No cases match these filters. Try a different search or status.').waitFor();
await p.getByLabel('Filter by status').selectOption('All statuses');await p.getByRole('button',{name:'View QS-001'}).waitFor();
await p.setViewportSize({width:390,height:844});assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await p.getByRole('button',{name:/Operator View/}).click();
await p.emulateMedia({reducedMotion:'reduce'});assert.equal(await p.locator('.demo-card').first().evaluate(e=>getComputedStyle(e).animationName),'none');
assert.deepEqual(errors,[]);console.log('PASS guided check, accessible progress and reset, case search/status filters in both views, downloaded .ics dates, mobile overflow, reduced motion, and no page errors');
await b.close();
