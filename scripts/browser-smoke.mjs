import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined,headless:true,args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173');
await page.getByRole('heading',{name:'1Now Quick Support.'}).waitFor();
await page.screenshot({path:'/tmp/1now-desktop.png',fullPage:true});
await page.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
assert.ok(await page.getByText('This field is required.').count()>=7);
console.log('PASS required fields');
await page.getByRole('button',{name:/Urgent Booking Conflict/}).click();
assert.equal(await page.getByLabel('Operator name').inputValue(),'Alex Morgan');
await page.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
await page.getByRole('heading',{name:'QS-001',exact:true}).waitFor();
assert.ok(await page.getByText('Direct · DR-1048').count());
await page.getByRole('button',{name:/Support Dashboard/}).click();
await page.getByLabel('Current status').selectOption('Investigating');
await page.getByLabel('Investigation note').fill('Reviewing both sample reservations with the operator.');
await page.getByRole('button',{name:'Save case update'}).click();
await page.getByLabel('Current status').selectOption('Resolved');
await page.getByRole('button',{name:'Save case update'}).click();
await page.getByRole('alert').filter({hasText:'Document a meaningful resolution'}).waitFor();
await page.getByLabel('Resolution note').fill('Demo review complete. Operator confirmed sample dates and agreed next steps; no external booking was changed.');
await page.getByRole('button',{name:'Save case update'}).click();
await page.getByText('Documented resolution',{exact:true}).waitFor();
await page.getByRole('button',{name:/Operator View/}).click();
await page.getByLabel('Tell support what is still happening').fill('My booked dates still appear available.');
await page.getByRole('button',{name:'Reopen ticket'}).click();
await page.getByText('Reopened: My booked dates still appear available.').waitFor();
console.log('PASS urgent creation, investigation, resolution guard, documented resolution and operator reopen');
await page.reload();
await page.getByRole('button',{name:/QS-001/}).click();
await page.getByText('Reopened: My booked dates still appear available.').waitFor();
console.log('PASS browser persistence after reload');
for (const [label,expected] of [['Calendar Disconnected','Calendar connection disconnected'],['No Known Conflict','No known conflict in sample records']]) {
 await page.getByRole('button',{name:new RegExp(label)}).click();
 await page.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
 await page.locator('.finding b').filter({hasText:expected}).waitFor();
}
console.log('PASS other two demo scenarios');
await page.getByRole('button',{name:/No Known Conflict/}).click();
await page.getByLabel('Calendar connection',{exact:false}).first().selectOption('Unknown');
await page.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
await page.locator('.finding b').filter({hasText:'Calendar connection needs verification'}).waitFor();
console.log('PASS unknown connection');
await page.getByLabel('Booking end date').fill('2026-11-01');
await page.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
await page.getByText('End date must be on or after the start date.').waitFor();
console.log('PASS reversed dates');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'/tmp/1now-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
console.log('PASS mobile layout without horizontal overflow');
await page.getByRole('button',{name:'Reset Demo Data',exact:false}).first().click();
await page.getByRole('button',{name:'Keep my tickets'}).click();
assert.equal(await page.getByRole('button',{name:/QS-00/}).count(),4);
await page.getByRole('button',{name:'Reset Demo Data',exact:false}).first().click();
await page.getByRole('alertdialog').getByRole('button',{name:'Reset Demo Data'}).click();
assert.equal(await page.getByRole('button',{name:/QS-00/}).count(),0);
await page.reload();
assert.equal(await page.getByRole('button',{name:/QS-00/}).count(),0);
console.log('PASS reset cancellation, reset and persisted reset');
assert.deepEqual(errors,[]); console.log('PASS no browser runtime errors');
await page.evaluate(() => localStorage.setItem('1now-quick-support-v1', '{broken'));
await page.reload();
await page.getByRole('alert').filter({hasText:'Saved data is unavailable'}).waitFor();
await page.getByRole('button',{name:/Urgent Booking Conflict/}).click();
await page.getByRole('button',{name:'Check Issue & Create Ticket'}).click();
assert.equal(await page.evaluate(()=>localStorage.getItem('1now-quick-support-v1')), '{broken');
console.log('PASS corrupt data warning and preservation');
await browser.close();
